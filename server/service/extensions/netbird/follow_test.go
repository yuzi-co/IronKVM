func TestIndexEntryChecks(t *testing.T) {
	good := indexEntry{Name: "netbird", Release: "0.82.0-r0", Arch: "riscv64", Size: 100, Installed: 100,
		Checksum: "Q1" + base64.StdEncoding.EncodeToString(make([]byte, 20)), Commit: testCommit}
	if err := good.check(); err != nil {
		t.Fatal(err)
	}
	for name, mutate := range map[string]func(*indexEntry){
		"name":          func(e *indexEntry) { e.Name = "netbird-ui" },
		"version form":  func(e *indexEntry) { e.Release = "0.82.0_rc1-r0" },
		"no release":    func(e *indexEntry) { e.Release = "0.82.0" },
		"q2 checksum":   func(e *indexEntry) { e.Checksum = "Q2" + base64.StdEncoding.EncodeToString(make([]byte, 32)) },
		"short sum":     func(e *indexEntry) { e.Checksum = "Q1AAAA" },
		"no commit":     func(e *indexEntry) { e.Commit = "" },
		"empty package": func(e *indexEntry) { e.Size = 0 },
	} {
		e := good
		mutate(&e)
		if err := e.check(); err == nil {
			t.Errorf("%s: accepted %+v", name, e)
		}
	}
}

// The real index and package, when given, read as the fake ones do. The
// container proof of ironkvm-dist #175 runs it against v3.24's files:
// NETBIRD_REAL_INDEX=APKINDEX.tar.gz NETBIRD_REAL_PACKAGE=netbird-....apk.
func TestRealIndexAndPackage(t *testing.T) {
	idx, pkg := os.Getenv("NETBIRD_REAL_INDEX"), os.Getenv("NETBIRD_REAL_PACKAGE")
	if idx == "" || pkg == "" {
		t.Skip("NETBIRD_REAL_INDEX and NETBIRD_REAL_PACKAGE are not set")
	}
	e, err := readIndex(idx)
	if err != nil {
		t.Fatal(err)
	}
	if err := e.check(); err != nil {
		t.Fatal(err)
	}
	if filepath.Base(pkg) != e.File() {
		t.Fatalf("the index names %s", e.File())
	}
	sum, err := matchEntry(pkg, e)
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("%s %s: %d bytes, %s, c:%s, sha256 %s", e.Name, e.Release, e.Size, e.Checksum, e.Commit, sum)
}

// The whole fallback against v3.24's real index and package and a real apk,
// when given: NETBIRD_REAL_DIR holds APKINDEX.tar.gz and the package it
// names, and NETBIRD_REAL_APK is apk-tools 3 with the riscv64 keys. The pin is
// served from another directory, where it is gone.
func TestRealFollow(t *testing.T) {
	dir, apk := os.Getenv("NETBIRD_REAL_DIR"), os.Getenv("NETBIRD_REAL_APK")
	if dir == "" || apk == "" {
		t.Skip("NETBIRD_REAL_DIR and NETBIRD_REAL_APK are not set")
	}
	fsroot := scratchImage(t, true)
	saved := ApkPath
	t.Cleanup(func() { ApkPath = saved })
	ApkPath = apk

	files := map[string][]byte{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if e.Name() == indexFile || strings.HasSuffix(e.Name(), ".apk") {
			b, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				t.Fatal(err)
			}
			files[e.Name()] = b
		}
	}
	serveMirror(t, files)
	release.Artifact.URL = strings.TrimSuffix(indexURL, indexFile) + "gone/" + packageFile

	if err := install(); err != nil {
		t.Fatal(err)
	}
	rec, ok := installer.ReadInstalled("netbird")
	if !ok {
		t.Fatal("no installed.json")
	}
	fi, err := os.Stat(fsroot + "/usr/bin/netbird")
	if err != nil {
		t.Fatal(err)
	}
	t.Logf("installed %s from %s, sha256 %s, source %s; binary %d bytes, sha256 %s",
		rec.Manifest.Version, rec.URL, rec.Manifest.Artifact.SHA256, rec.Source, fi.Size(), rec.Sums["netbird"])
}
