const testCommit = "0123456789abcdef0123456789abcdef01234567"

// tarMember is one gzip member of an Alpine v2 file: a tar of files, cut
// before the end-of-archive blocks unless last, as abuild writes them.
func tarMember(t *testing.T, files [][2]string, last bool) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for _, f := range files {
		mode := int64(0o644)
		if strings.HasPrefix(f[0], "usr/bin/") {
			mode = 0o755
		}
		if err := tw.WriteHeader(&tar.Header{Name: f[0], Mode: mode, Size: int64(len(f[1]))}); err != nil {
			t.Fatal(err)
		}
		if _, err := tw.Write([]byte(f[1])); err != nil {
			t.Fatal(err)
		}
	}
	var err error
	if last {
		err = tw.Close()
	} else {
		err = tw.Flush()
	}
	if err != nil {
		t.Fatal(err)
	}
	if err := gz.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// alpinePackage is a package laid out as Alpine's v2 packages are: a
// signature member, a control member with .PKGINFO, and the data. It returns
// the package and the C: checksum of its control member.
func alpinePackage(t *testing.T, name, rel, arch, binary string) ([]byte, string) {
	t.Helper()
	sig := tarMember(t, [][2]string{{".SIGN.RSA.test.rsa.pub", "signature"}}, false)
	control := tarMember(t, [][2]string{{".PKGINFO", fmt.Sprintf("# Generated by abuild\npkgname = %s\npkgver = %s\narch = %s\nsize = 1\n", name, rel, arch)}}, false)
	data := tarMember(t, [][2]string{{"usr/bin/netbird", binary}}, true)
	sum := sha1.Sum(control)
	return append(append(append([]byte{}, sig...), control...), data...), "Q1" + base64.StdEncoding.EncodeToString(sum[:])
}

// entry is an APKINDEX record.
type entry struct {
	name, rel, arch, checksum, commit string
	size, installed                   int64
}

func (e entry) String() string {
	return fmt.Sprintf("C:%s\nP:%s\nV:%s\nA:%s\nS:%d\nI:%d\nT:test\nc:%s\n", e.checksum, e.name, e.rel, e.arch, e.size, e.installed, e.commit)
}

// goodEntry describes pkg as netbird rel for riscv64.
func goodEntry(pkg []byte, rel, checksum string) entry {
	return entry{name: "netbird", rel: rel, arch: "riscv64", checksum: checksum, commit: testCommit, size: int64(len(pkg)), installed: 4096}
}

// alpineIndex is an APKINDEX.tar.gz listing the records.
func alpineIndex(t *testing.T, records ...fmt.Stringer) []byte {
	t.Helper()
	var text strings.Builder
	text.WriteString("C:Q1aaaaaaaaaaaaaaaaaaaaaaaaaaa=\nP:other\nV:1.0-r0\nA:riscv64\nS:10\nI:10\n\n")
	for _, r := range records {
		text.WriteString(r.String())
		text.WriteString("\n")
	}
	sig := tarMember(t, [][2]string{{".SIGN.RSA.test.rsa.pub", "signature"}}, false)
	idx := tarMember(t, [][2]string{{"DESCRIPTION", "v3.24.0"}, {"APKINDEX", text.String()}}, true)
	return append(sig, idx...)
}

// mirror serves files by name over TLS, and 404 for any other; status forces
// a status for a name. It logs every path asked for.
type mirror struct {
	mu     sync.Mutex
	asked  []string
	files  map[string][]byte
	status map[string]int
}

func (m *mirror) requested(name string) bool {
	m.mu.Lock()
	defer m.mu.Unlock()
	for _, a := range m.asked {
		if a == name {
			return true
		}
	}
	return false
}

// serveMirror points the pin and the index at a fake mirror. The pin keeps
// its real file name and gets a sum of nothing served.
func serveMirror(t *testing.T, files map[string][]byte) *mirror {
	t.Helper()
	m := &mirror{files: files, status: map[string]int{}}
	srv := httptest.NewTLSServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		name := strings.TrimPrefix(r.URL.Path, "/")
		m.mu.Lock()
		m.asked = append(m.asked, name)
		code, forced := m.status[name]
		body, ok := m.files[name]
		m.mu.Unlock()
		switch {
		case forced:
			w.WriteHeader(code)
		case !ok:
			http.NotFound(w, r)
		default:
			_, _ = w.Write(body)
		}
	}))
	t.Cleanup(srv.Close)

	savedPin, savedDownloads, savedIndex := release, downloads, indexURL
	t.Cleanup(func() { release, downloads, indexURL = savedPin, savedDownloads, savedIndex })
	release.Artifact.URL = srv.URL + "/" + packageFile
	release.Artifact.SHA256 = sha256Hex([]byte("the pinned package"))
	indexURL = srv.URL + "/" + indexFile
	downloads = upstream.NewClient(srv.URL, srv.Client())
	noIndex(t)
	lookupIndex = fetchIndex
	return m
}

// followed is the common case: the pin is gone and the index names rel.
func followed(t *testing.T, rel string) (*mirror, []byte) {
	t.Helper()
	pkg, sum := alpinePackage(t, "netbird", rel, "riscv64", "netbird "+rel+"\n")
	file := "netbird-" + rel + ".apk"
	m := serveMirror(t, map[string][]byte{
		indexFile: alpineIndex(t, goodEntry(pkg, rel, sum)),
		file:      pkg,
	})
	return m, pkg
}

func TestInstallFollowsTheIndexWhenThePinIsGone(t *testing.T) {
	fsroot := scratchImage(t, true)
	calls := fakeApk(t)
	m, pkg := followed(t, "0.82.0-r1")

	if err := install(); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(addon.Dir("netbird"), "netbird")
	if b, err := os.ReadFile(bin); err != nil || string(b) != "netbird 0.82.0-r1\n" {
		t.Fatalf("the index's build is not installed: %q %v", b, err)
	}
	if target, err := os.Readlink(fsroot + "/usr/bin/netbird"); err != nil || target != bin {
		t.Fatalf("/usr/bin/netbird is not a link into the add-on: %q %v", target, err)
	}
	if !m.requested(packageFile) {
		t.Fatal("the pin must be tried first")
	}

	rec, ok := installer.ReadInstalled("netbird")
	if !ok {
		t.Fatal("no installed.json")
	}
	if rec.Manifest.Version != "0.82.0" || rec.Manifest.Artifact.SHA256 != sha256Hex(pkg) {
		t.Fatalf("the record must hold the version and sum installed: %+v", rec.Manifest)
	}
	if !strings.HasSuffix(rec.URL, "/netbird-0.82.0-r1.apk") || rec.Manifest.Artifact.URL != rec.URL {
		t.Fatalf("the record names %q", rec.URL)
	}
	if rec.Source != "https://gitlab.alpinelinux.org/alpine/aports/-/tree/"+testCommit+"/community/netbird" {
		t.Fatalf("the source must be the index's aports commit: %s", rec.Source)
	}

	got := callsOf(t, calls)
	last := -1
	for _, want := range []string{"verify ", indexFile, "verify ", "netbird-0.82.0-r1.apk", "extract "} {
		i := strings.Index(got[last+1:], want)
		if i < 0 {
			t.Fatalf("want %q after the previous step in:\n%s", want, got)
		}
		last += 1 + i
	}
	if e, ok := knownIndex(); !ok || e.Release != "0.82.0-r1" {
		t.Fatalf("the install must leave the index's build for the update offer: %+v", e)
	}
}

// The pin is the same build as the index's while both are on the mirror, and
// the index is not read at all.
func TestInstallPrefersThePin(t *testing.T) {
	scratchImage(t, true)
	fakeApk(t)
	pin, _ := alpinePackage(t, "netbird", pinRelease, "riscv64", "netbird pinned\n")
	m := serveMirror(t, map[string][]byte{packageFile: pin})
	release.Artifact.SHA256 = sha256Hex(pin)

	if err := install(); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(addon.Dir("netbird"), "netbird")); string(b) != "netbird pinned\n" {
		t.Fatalf("got %q", b)
	}
	if m.requested(indexFile) {
		t.Fatal("the index must not be read while the pin is there")
	}
}

// Only a 404 is followed: a server error, an offline board or a mismatched
// pin stays a failure.
func TestInstallDoesNotFollowOtherFailures(t *testing.T) {
	fsroot := scratchImage(t, true)
	calls := fakeApk(t)
	m, _ := followed(t, "0.82.0-r0")
	m.status[packageFile] = http.StatusInternalServerError

	err := install()
	if err == nil || !strings.Contains(err.Error(), "status 500") {
		t.Fatalf("got %v", err)
	}
	if m.requested(indexFile) {
		t.Fatal("a server error must not fall back to the index")
	}
	assertNothingLeft(t, fsroot, calls)

	// A pin served with another sum is a mismatch, not a missing file.
	m.mu.Lock()
	delete(m.status, packageFile)
	m.files[packageFile] = []byte("another package")
	m.mu.Unlock()
	if err := install(); err == nil || !strings.Contains(err.Error(), "checksum mismatch") {
		t.Fatalf("got %v", err)
	}
	if m.requested(indexFile) {
		t.Fatal("a mismatched pin must not fall back to the index")
	}
}

// refused runs an install that must fail with want and leave nothing.
func refused(t *testing.T, fsroot string, want string) {
	t.Helper()
	err := install()
	if err == nil || !strings.Contains(err.Error()+" "+vpn.Message("install failed", err), want) {
		t.Fatalf("want %q, got %v", want, err)
	}
	if _, err := os.Lstat(fsroot + "/usr/bin/netbird"); err == nil {
		t.Fatal("nothing may be installed")
	}
	if _, err := os.Stat(addon.Dir("netbird")); err == nil {
		t.Fatal("a failed first install must leave no add-on directory behind")
	}
}

