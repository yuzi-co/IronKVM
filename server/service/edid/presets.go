// Origin says who made a preset.
type Origin string

const (
	// OriginGenerated presets are written by Build from a spec in this file.
	OriginGenerated Origin = "generated"
	// OriginSipeed is the EDID Sipeed ships with nanokvm_update_edid.
	OriginSipeed Origin = "sipeed"
	// OriginBridge is the EDID built into the LT6911UXC firmware.
	OriginBridge Origin = "bridge"
)

// Preset is one EDID in the library. CapturedOn lists the boot slots ("a" for
// the vendor kernel, "b" for mainline) whose capture took the preset's
// preferred mode in the bench trials, with the EDID given to the host as an
// override; it says nothing about writing the preset to the bridge, which
// nobody has done.
type Preset struct {
	ID         string   `json:"id"`
	Name       string   `json:"name"`
	Origin     Origin   `json:"origin"`
	Source     string   `json:"source"`
	Licence    string   `json:"licence"`
	CapturedOn []string `json:"capturedOn"`
	Size       int      `json:"size"`
	SHA256     string   `json:"sha256"`
	Preferred  *Timing  `json:"preferred"`
}

var ErrUnknownPreset = errors.New("no such EDID preset")

