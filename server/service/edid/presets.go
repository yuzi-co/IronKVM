var presets = func() []Preset {
	var out []Preset
	for _, g := range generated {
		p := g.Preset
		p.Origin = OriginGenerated
		p.Licence = generatedLicence
		out = append(out, p)
	}
	out = append(out, copied...)
	for i := range out {
		data, err := presetFiles.ReadFile("presets/" + out[i].ID + ".bin")
		if err != nil {
			// A generated preset whose file is missing: the tests say which.
			continue
		}
		sum := sha256.Sum256(data)
		out[i].Size = len(data)
		out[i].SHA256 = hex.EncodeToString(sum[:])
		if info, err := Parse(data); err == nil {
			out[i].Preferred = info.Preferred
		}
	}
	return out
}()

// Presets lists the library, generated presets first.
func Presets() []Preset {
	return append([]Preset(nil), presets...)
}

// PresetData returns the bytes of the preset named id.
func PresetData(id string) ([]byte, error) {
	for _, p := range presets {
		if p.ID == id {
			return presetFiles.ReadFile("presets/" + id + ".bin")
		}
	}
	return nil, ErrUnknownPreset
}
